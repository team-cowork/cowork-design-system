import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (file) =>
  JSON.parse(readFileSync(new URL(`tokens/${file}`, root), 'utf8'));

export function loadTokens() {
  return {
    base: {
      ...read('color.json'),
      ...read('typography.json'),
      ...read('dimension.json'),
    },
    light: read('semantic.light.json'),
    dark: read('semantic.dark.json'),
  };
}

function leaves(node, path = []) {
  if ('$value' in node) return [{ path, value: node.$value }];
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => leaves(child, [...path, key]));
}

const refPath = (value) => /^\{(.+)\}$/.exec(value)?.[1].split('.');

function lookup(tree, path) {
  const node = path.reduce((acc, key) => acc?.[key], tree);
  if (!node || !('$value' in node))
    throw new Error(`Unknown token reference: {${path.join('.')}}`);
  return node.$value;
}

const kebab = (path) => path.join('-');
const camel = (parts) =>
  parts
    .flatMap((part) => part.split('-'))
    .map((word, i) => (i === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join('');
const rem = (px) => `${px / 16}rem`;

const primitiveVar = (path) => `--cowork-primitive-${kebab(path.slice(1))}`;
const semanticVar = (name) => `--cowork-semantic-${name}`;

const typographyVar = (path, prop) =>
  `--cowork-typography-${kebab(path)}-${prop}`;

function semanticDecls(tree, base) {
  return leaves(tree.semantic).map(({ path, value }) => {
    const ref = refPath(value);
    if (ref) lookup(base, ref);
    return `  ${semanticVar(kebab(path))}: ${ref ? `var(${primitiveVar(ref)})` : value};`;
  });
}

export function buildCss({ base, light, dark }) {
  const colors = leaves(base.color);
  const palettes = colors.filter(({ path }) => path.length > 1);
  const semanticNames = leaves(light.semantic).map(({ path }) => kebab(path));
  const weights = leaves(base.font.weight);
  const styles = leaves(base.typography);
  const dims = ['spacing', 'radius', 'size'].flatMap((group) =>
    leaves(base[group]).map(
      ({ path, value }) => `  --cowork-${group}-${kebab(path)}: ${value}px;`,
    ),
  );
  const family = base.font.family.$value.map((f) =>
    f.includes(' ') ? `'${f}'` : f,
  );

  return `/* Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit. */

:root {
${colors.map(({ path, value }) => `  ${primitiveVar(['color', ...path])}: ${value};`).join('\n')}

${semanticDecls(light, base).join('\n')}

${dims.join('\n')}

${styles
  .flatMap(({ path, value }) => [
    `  ${typographyVar(path, 'font-size')}: ${rem(value.fontSize)};`,
    `  ${typographyVar(path, 'line-height')}: ${rem(value.lineHeight)};`,
  ])
  .join('\n')}
}

.dark {
${semanticDecls(dark, base).join('\n')}
}

@theme inline {
  --font-cowork: ${[...family, 'system-ui', 'sans-serif'].join(', ')};

${weights.map(({ path, value }) => `  --font-weight-${kebab(path)}: ${value};`).join('\n')}

${palettes.map(({ path }) => `  --color-cowork-${kebab(path)}: var(${primitiveVar(['color', ...path])});`).join('\n')}

${semanticNames.map((name) => `  --color-${name}: var(${semanticVar(name)});`).join('\n')}
}
${styles
  .map(({ path, value }) => {
    const name = kebab(path);
    const weight = refPath(value.fontWeight);
    lookup(base, weight);
    return `
@utility typography-${name} {
  font-family: var(--font-cowork);
  font-size: var(${typographyVar(path, 'font-size')});
  font-weight: var(--font-weight-${weight.at(-1)});
  letter-spacing: 0;
  line-height: var(${typographyVar(path, 'line-height')});
}`;
  })
  .join('\n')}
`;
}

const dartColor = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const dartIdent = (prefix, path) =>
  /^\d/.test(path[0]) ? `${prefix}${camel(path)}` : camel(path);

function dartSemantic(className, tree, base) {
  const fields = leaves(tree.semantic).map(({ path, value }) => {
    const ref = refPath(value);
    if (ref) lookup(base, ref);
    const expr = ref
      ? `CoworkPrimitiveColors.${camel(ref.slice(1))}`
      : dartColor(value);
    return `  static const Color ${camel(path)} = ${expr};`;
  });
  return `abstract final class ${className} {\n${fields.join('\n')}\n}`;
}

function dartDimensions(className, prefix, tree) {
  const fields = leaves(tree).map(
    ({ path, value }) =>
      `  static const double ${dartIdent(prefix, path)} = ${value.toFixed(1)};`,
  );
  return `abstract final class ${className} {\n${fields.join('\n')}\n}`;
}

export function buildDart({ base, light, dark }) {
  const [family, ...fallback] = base.font.family.$value;
  const styles = leaves(base.typography).map(({ path, value }) => {
    const weight = lookup(base, refPath(value.fontWeight));
    return `  static const TextStyle ${camel(path)} = TextStyle(
    fontFamily: fontFamily,
    fontFamilyFallback: fontFamilyFallback,
    fontSize: ${value.fontSize},
    height: ${value.lineHeight} / ${value.fontSize},
    fontWeight: FontWeight.w${weight},
    letterSpacing: 0,
  );`;
  });

  return `// Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit.

import 'package:flutter/painting.dart';

abstract final class CoworkPrimitiveColors {
${leaves(base.color)
  .map(
    ({ path, value }) =>
      `  static const Color ${camel(path)} = ${dartColor(value)};`,
  )
  .join('\n')}
}

${dartSemantic('CoworkLightColors', light, base)}

${dartSemantic('CoworkDarkColors', dark, base)}

abstract final class CoworkTypography {
  static const String fontFamily = '${family}';
  static const List<String> fontFamilyFallback = [${fallback.map((f) => `'${f}'`).join(', ')}];

${styles.join('\n\n')}
}

${dartDimensions('CoworkSpacing', 's', base.spacing)}

${dartDimensions('CoworkRadius', 'r', base.radius)}

${dartDimensions('CoworkSize', 's', base.size)}
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tokens = loadTokens();
  writeFileSync(
    new URL('packages/web/src/styles/tokens.css', root),
    buildCss(tokens),
  );
  writeFileSync(
    new URL('packages/flutter/lib/cowork_design_tokens.dart', root),
    buildDart(tokens),
  );
  console.log(
    'tokens → packages/web/src/styles/tokens.css, packages/flutter/lib/cowork_design_tokens.dart',
  );
}
